/**
 * Renders the three OTHM-layout documents (see othmModel) as Word files: the Qualification
 * Specification, the Unit Specifications and the Assignment Briefs.
 *
 * The layout follows OTHM's (Rejin, 13 October 2026), under the programme's own name: no
 * awarding body's logo or regulator numbers. Unit specifications are landscape, as OTHM's are,
 * so the outcome, criteria and content columns have room.
 */
import {
  AlignmentType,
  Document,
  Footer,
  Header,
  HeadingLevel,
  Packer,
  PageBreak,
  PageNumber,
  PageOrientation,
  Paragraph,
  ShadingType,
  Table,
  TableCell,
  TableLayoutType,
  TableRow,
  TextRun,
  WidthType,
} from 'docx';
import { xmlSafeDeep } from '../../utils/xmlSafe';
import { NOT_STATED, OthmQualification, OthmUnit, othmQualification } from './othmModel';

const FONT = 'Arial';
const BODY = 20; // 10pt
const SMALL = 16;
const PORTRAIT = 11906 - 2 * 1134;
const LANDSCAPE = 16838 - 2 * 1134;
const MISSING_CRITERIA =
  'Assessment criteria not yet written. Use “Prepare OTHM documents” to write them.';

const run = (
  t: string,
  o: { bold?: boolean; italics?: boolean; size?: number; color?: string } = {}
) =>
  new TextRun({
    text: t,
    font: FONT,
    size: o.size || BODY,
    bold: o.bold,
    italics: o.italics,
    color: o.color,
  });
const para = (t: string, o: { bold?: boolean; italics?: boolean; after?: number } = {}) =>
  new Paragraph({ children: [run(t, o)], spacing: { after: o.after ?? 100 } });
const bullet = (t: string) =>
  new Paragraph({ children: [run(t)], bullet: { level: 0 }, spacing: { after: 40 } });
const heading = (
  t: string,
  level: (typeof HeadingLevel)[keyof typeof HeadingLevel] = HeadingLevel.HEADING_1
) =>
  new Paragraph({
    heading: level,
    children: [run(t, { bold: true, size: level === HeadingLevel.HEADING_1 ? 26 : 22 })],
    spacing: { before: 240, after: 100 },
  });
const pageBreak = () => new Paragraph({ children: [new PageBreak()] });

function cell(
  lines: string | string[],
  width: number,
  total: number,
  o: { bold?: boolean; fill?: string } = {}
) {
  const items = (Array.isArray(lines) ? lines : [lines]).filter((l) => l !== undefined);
  return new TableCell({
    width: { size: Math.round((width / 100) * total), type: WidthType.DXA },
    shading: o.fill ? { type: ShadingType.CLEAR, color: 'auto', fill: o.fill } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: (items.length ? items : ['']).map((l) => para(l, { bold: o.bold, after: 40 })),
  });
}

function table(
  header: string[] | null,
  rows: (string | string[])[][],
  widths: number[],
  total: number
) {
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths.map((w) => Math.round((w / 100) * total)),
    layout: TableLayoutType.FIXED,
    rows: [
      ...(header
        ? [
            new TableRow({
              tableHeader: true,
              children: header.map((h, i) =>
                cell(h, widths[i], total, { bold: true, fill: 'E7E6E6' })
              ),
            }),
          ]
        : []),
      ...rows.map(
        (r) =>
          new TableRow({
            cantSplit: true,
            children: r.map((c, i) => cell(c, widths[i], total, { bold: !header && i === 0 })),
          })
      ),
    ],
  });
}

function chrome(label: string) {
  return {
    headers: {
      default: new Header({
        children: [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [run(label.toUpperCase(), { size: SMALL, color: '555555' })],
          }),
        ],
      }),
    },
    footers: {
      default: new Footer({
        children: [
          new Paragraph({
            alignment: AlignmentType.RIGHT,
            children: [
              new TextRun({
                children: ['PAGE ', PageNumber.CURRENT, ' OF ', PageNumber.TOTAL_PAGES],
                font: FONT,
                size: SMALL,
                color: '555555',
              }),
            ],
          }),
        ],
      }),
    },
  };
}

const monthYear = (d: Date) => d.toLocaleDateString('en-GB', { month: 'long', year: 'numeric' });

function cover(title: string, kind: string, now: Date): Paragraph[] {
  return [
    new Paragraph({ spacing: { before: 3000 }, children: [run(title, { bold: true, size: 44 })] }),
    para(`${kind} | ${monthYear(now)}`, { after: 400 }),
    para(
      'Generated by the Curriculum Generator as a draft for review. Items marked “To be assigned” are completed by the awarding body; items marked “Not yet stated” are completed by the institution.',
      { italics: true }
    ),
  ];
}

function unitHeaderTable(u: OthmUnit, total: number) {
  return table(
    null,
    [
      ['Unit Reference Number', u.code],
      ['Unit Title', u.title],
      ['Unit Level', u.level],
      ['Number of Credits', String(u.credits)],
      ['Total Qualification Time (TQT)', u.tqt === '' ? '' : `${u.tqt} Hours`],
      ['Guided Learning Hours (GLH)', u.glh === '' ? '' : `${u.glh} Hours`],
      ['Mandatory / Optional', u.status],
      ['Unit Grading Structure', u.grading],
    ],
    [35, 65],
    total
  );
}

/** One unit's specification, as in OTHM's Unit Specifications and the Qualification Specification. */
export function unitSpecification(u: OthmUnit): (Paragraph | Table)[] {
  const W = LANDSCAPE;
  return [
    heading(u.title),
    unitHeaderTable(u, W),
    heading('Unit Aims', HeadingLevel.HEADING_2),
    para(u.aim || NOT_STATED),
    heading(
      'Learning Outcomes, Assessment Criteria and Indicative Content',
      HeadingLevel.HEADING_2
    ),
    table(
      [
        'Learning Outcomes – The learner will:',
        'Assessment Criteria – The learner can:',
        'Indicative content',
      ],
      u.outcomes.map((o) => [
        `${o.number}. ${o.statement}`,
        o.missing ? [MISSING_CRITERIA] : o.criteria.map((c) => `${c.ref} ${c.text}`),
        o.indicativeContent.length ? o.indicativeContent.map((c) => `• ${c}`) : [''],
      ]),
      [30, 37, 33],
      W
    ),
    heading('Assessment', HeadingLevel.HEADING_2),
    para(
      'To achieve a ‘pass’ for this unit, learners must provide evidence to demonstrate that they have fulfilled all the learning outcomes and meet the standards specified by all assessment criteria.'
    ),
    u.assessment.length
      ? table(
          [
            'Learning Outcomes to be met',
            'Assessment criteria to be covered',
            'Type of assessment',
            'Word count (approx. length of coursework)',
          ],
          u.assessment.map((a) => [a.outcomes, a.criteria, a.type, a.length]),
          [22, 26, 22, 30],
          W
        )
      : para('No assessment has been generated for this unit yet (Steps 7 and 12).', {
          italics: true,
        }),
    heading('Indicative Reading list', HeadingLevel.HEADING_2),
    ...(u.readings.length
      ? u.readings.map((r) => para(r))
      : [para('No readings yet (Step 6).', { italics: true })]),
    ...(u.links.length
      ? [
          heading('Website Links', HeadingLevel.HEADING_2),
          ...u.links.flatMap((l) => [para(l.url, { after: 0 }), para(l.title)]),
        ]
      : []),
  ];
}

function document(
  sections: { landscape?: boolean; label: string; children: (Paragraph | Table)[] }[]
): Promise<Buffer> {
  const doc = new Document({
    styles: { default: { document: { run: { font: FONT, size: BODY } } } },
    sections: sections.map((s) => ({
      properties: {
        page: {
          size: s.landscape
            ? { width: 11906, height: 16838, orientation: PageOrientation.LANDSCAPE }
            : { width: 11906, height: 16838 },
          margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 },
        },
      },
      ...chrome(s.label),
      children: s.children,
    })),
  });
  return Packer.toBuffer(doc);
}

/** The Qualification Specification: front matter, then every unit's specification. */
export async function qualificationSpecificationDocx(
  workflow: any,
  now = new Date()
): Promise<Buffer> {
  const q: OthmQualification = xmlSafeDeep(othmQualification(workflow));
  const label = `${q.title} Specification`;
  const front: (Paragraph | Table)[] = [
    ...cover(q.title, 'Specification', now),
    pageBreak(),
    heading('Qualification Objectives'),
    para(q.description || NOT_STATED),
    ...(q.aims.length
      ? [para('The qualification aims:', { bold: true }), ...q.aims.map(bullet)]
      : []),
    heading('Quality, Standards and Recognitions'),
    para(`Recognition and regulation of this qualification: ${NOT_STATED.toLowerCase()}`),
    heading('Regulatory Information'),
    table(null, q.regulatory, [40, 60], PORTRAIT),
    heading('Equivalences'),
    para(
      `Level: ${q.level}. Equivalence to other qualifications is ${'to be confirmed by the awarding body'}.`
    ),
    heading('Qualification Structure'),
    para(q.structure),
    table(
      ['Unit Ref. No.', 'Unit title', 'Credit', 'GLH', 'TQT'],
      q.units.map((u) => [u.code, u.title, String(u.credits), String(u.glh), String(u.tqt)]),
      [16, 54, 10, 10, 10],
      PORTRAIT
    ),
    heading('Definitions'),
    para(
      'Total Qualification Time (TQT) is the number of notional hours which represents an estimate of the total amount of time that could reasonably be expected to be required in order for a learner to achieve and demonstrate the achievement of the level of attainment necessary for the award of a qualification. It comprises Guided Learning and the hours a learner spends in preparation, study and assessment as directed by, but not under the immediate supervision of, a tutor.'
    ),
    para(
      'Guided Learning Hours (GLH) are the hours that a teacher, lecturer or other member of staff is available to provide immediate teaching support or supervision to a learner.'
    ),
    para(
      `Credit value is the number of credits awarded for the successful achievement of the learning outcomes of a unit. ${q.creditNote}`
    ),
    heading('Entry Requirements'),
    ...(q.entryIsProposal
      ? [para('Proposal: requires institutional approval.', { bold: true })]
      : []),
    ...q.entryRequirements
      .split('\n')
      .filter(Boolean)
      .map((l) => para(l)),
    heading('Progression'),
    ...(q.progression.length ? q.progression.map(bullet) : [para(NOT_STATED)]),
    heading('Delivery'),
    para(q.delivery),
    para(
      'The Guided Learning Hours listed for each unit give the hours of teacher-supervised or direct study likely to be required to teach that unit.'
    ),
    heading('Assessment and Verification'),
    ...q.assessment.map((l) => para(l)),
    para(
      'Specific assessment guidance and the marking criteria for each unit are in the Assignment Briefs.'
    ),
    heading('Opportunities for Learners to Pass'),
    para(q.opportunitiesToPass),
    heading('Equality and Diversity'),
    para(q.equality),
    ...(q.unitsMissingCriteria.length
      ? [
          para(
            `Assessment criteria are not yet written for: ${q.unitsMissingCriteria.join(', ')}.`,
            { italics: true }
          ),
        ]
      : []),
  ];
  return document([
    { label, children: front },
    ...q.units.map((u) => ({ landscape: true, label, children: unitSpecification(u) })),
    {
      label,
      children: [
        heading('Important Note'),
        para(
          'This specification is a guide to the qualification. Procedures, regulations, fees and timetables may change during the course of study; learners should confirm current information with the institution.'
        ),
      ],
    },
  ]);
}

/** The Unit Specifications alone. */
export async function unitSpecificationsDocx(workflow: any, now = new Date()): Promise<Buffer> {
  const q = xmlSafeDeep(othmQualification(workflow));
  const label = `${q.title} Unit Specifications`;
  return document([
    { label, children: cover(q.title, 'Unit Specifications', now) },
    ...q.units.map((u) => ({ landscape: true, label, children: unitSpecification(u) })),
  ]);
}

/** Generic Pass / Fail guidance for criterion-referenced marking, at the programme's level. */
function markingGuidance(level: string): (Paragraph | Table)[] {
  const l = level.toLowerCase();
  const levelLine = /master|level 7|postgrad/.test(l)
    ? 'Engages critically with academic debate, with clear synthesis of theory and practice and a critical analysis that results in originality.'
    : /bachelor|degree|level 6/.test(l)
      ? 'Makes excellent links between ideas, theories and practice, and engages critically and analytically with a wide range of relevant sources.'
      : 'Gives a full, independent response that applies relevant theory, concepts and models well beyond the taught material.';
  return [
    heading('Assessment Guidance for Criterion Referenced Marking'),
    para(
      'These generic descriptors characterise the standard expected at this level. They apply mainly, though not exclusively, to written academic work. Unit-specific requirements, such as word counts, are stated in each assignment brief.'
    ),
    table(
      ['Result', `Descriptor (${level})`],
      [
        [
          'Pass',
          [
            'Addresses every task and meets every assessment criterion of the unit.',
            levelLine,
            'Uses independently sourced material, applied to the scenario and referenced accurately.',
            'Clearly structured, with very few errors in referencing, grammar or syntax.',
          ],
        ],
        [
          'Fail',
          [
            'One or more learning outcomes or assessment criteria are not met.',
            'Little attempt to engage with the assignment brief.',
            'Inadequate knowledge or understanding of key concepts, theories or practice.',
            'Largely descriptive, with very limited analysis, synthesis or evaluation.',
          ],
        ],
      ],
      [14, 86],
      PORTRAIT
    ),
  ];
}

function unitBrief(u: OthmUnit): (Paragraph | Table)[] {
  const b = u.brief;
  return [
    heading(u.title.toUpperCase()),
    unitHeaderTable(u, PORTRAIT),
    heading('Unit Aims', HeadingLevel.HEADING_2),
    para(u.aim || NOT_STATED),
    table(
      ['Learning Outcomes – the learner will:', 'Assessment Criteria – the learner can:'],
      u.outcomes.map((o) => [
        `${o.number}. ${o.statement}`,
        o.missing ? [MISSING_CRITERIA] : o.criteria.map((c) => `${c.ref} ${c.text}`),
      ]),
      [40, 60],
      PORTRAIT
    ),
    ...(b
      ? [
          heading('Scenario', HeadingLevel.HEADING_2),
          para(b.scenario || 'No scenario was written for this assessment.'),
          heading(b.taskHeading, HeadingLevel.HEADING_2),
          para('Instructions', { bold: true }),
          ...(b.intro ? [para(b.intro)] : []),
          para(`Your ${b.type.toLowerCase()} must:`),
          ...b.instructions.map(bullet),
          ...(b.deliverables.length
            ? [para('You will produce:', { bold: true }), ...b.deliverables.map(bullet)]
            : []),
          para('Delivery and Submission:', { bold: true }),
          ...(b.submission.length
            ? b.submission.map(bullet)
            : [bullet('As stated by your tutor.')]),
          para('Referencing:', { bold: true }),
          bullet('Each section must reflect any supporting Harvard style citations.'),
          bullet(
            'A comprehensive Harvard style reference list must be included at the end of the work.'
          ),
          para('Evidence to be submitted:', { bold: true }),
          ...(b.evidence.length ? b.evidence.map(bullet) : [bullet(b.type)]),
        ]
      : [
          para(
            'No assessment has been generated for this unit yet. Generate Step 12 (Assignment Packs) first.',
            { italics: true }
          ),
        ]),
  ];
}

/** The Assignment Briefs: marking guidance, then one brief per unit. */
export async function assignmentBriefsDocx(workflow: any, now = new Date()): Promise<Buffer> {
  const q = xmlSafeDeep(othmQualification(workflow));
  const label = `${q.title} | Assignment Briefs`;
  return document([
    {
      label,
      children: [
        ...cover(q.title, 'Assignment Briefs', now),
        pageBreak(),
        ...markingGuidance(q.level),
      ],
    },
    ...q.units.map((u) => ({ label, children: unitBrief(u) })),
  ]);
}

